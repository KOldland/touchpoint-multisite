                }
                $html .= '</ul>';
            }
            $html .= '</div>';
        }

        if ( ! empty( $phase2['ranked_keywords'] ) ) {
            $html .= '<h2>Phase 2: Strategic Keywords</h2>';
            $html .= '<div class="section"><table><thead><tr><th>Keyword</th><th>Volume</th><th>Priority</th></tr></thead><tbody>';
            foreach ( array_slice( $phase2['ranked_keywords'], 0, 10 ) as $kw ) {
                $html .= '<tr>';
                $html .= '<td>' . esc_html( $kw['keyword'] ) . '</td>';
                $html .= '<td>' . esc_html( $kw['search_volume'] ?? 'N/A' ) . '</td>';
                $html .= '<td>' . esc_html( $kw['priority_score'] ?? '0' ) . '</td>';
                $html .= '</tr>';
            }
            $html .= '</tbody></table></div>';
        }

        if ( ! empty( $phase3['prioritized_topics'] ) ) {
            $html .= '<h2>Phase 3: Topic Framing</h2><div class="section">';
            foreach ( $phase3['prioritized_topics'] as $topic ) {
                $html .= '<h3>' . esc_html( $topic['topic'] ) . '</h3>';
                $html .= '<p><strong>Strategic Intent:</strong> ' . esc_html( $topic['why_now'] ?? '' ) . '</p>';
                if ( ! empty( $topic['key_findings'] ) ) {
                    $html .= '<p><strong>Key Findings:</strong></p><ul>';
                    foreach ( $topic['key_findings'] as $finding ) {
                        $html .= '<li>' . esc_html( $finding ) . '</li>';
                    }
                    $html .= '</ul>';
                }
            }
            $html .= '</div>';
        }

        if ( ! empty( $synopses['synopses'] ) ) {
            $html .= '<h2>Final Article Synopses</h2><div class="section">';
            foreach ( $synopses['synopses'] as $s ) {
                $html .= '<div class="synopsis-card">';
                $html .= '<h3>ARTICLE: ' . esc_html( $s['headline'] ?? 'Untitled' ) . '</h3>';
                $html .= '<p><strong>Summary:</strong> ' . esc_html( $s['summary'] ?? '' ) . '</p>';
                if ( ! empty( $s['key_points'] ) ) {
                    $html .= '<p><strong>Key Points:</strong></p><ul>';
                    foreach ( (array) $s['key_points'] as $kp ) {
                        $html .= '<li>' . esc_html( $kp ) . '</li>';
                    }
                    $html .= '</ul>';
                }
                $html .= '</div>';
            }
            $html .= '</div>';
        }

        // Provenance Appendix (inside body, before closing tags)
        $html .= $this->generate_provenance_appendix_html( $post_id );

        $html .= '
</body>
</html>';

        $filename = 'session-' . $post_id . '-' . date('Y-m-d-H-i-s') . '.html';
        $filepath = $this->get_export_path( $filename );

        file_put_contents( $filepath, $html );
        $file_url = $this->get_export_url( $filename );

        update_post_meta( $post_id, 'kh_planner_export_html_url', $file_url );

        return [
            'file_url' => $file_url,
            'file_path' => $filepath,
            'filename' => $filename,
        ];
    }

