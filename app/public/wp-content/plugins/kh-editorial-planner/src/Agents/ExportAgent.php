        th { background-color: #f9f9f9; }
        .section { margin-bottom: 30px; }
        .synopsis-card { background: #f9f9f9; padding: 20px; margin-bottom: 20px; border-left: 4px solid #333; }
        .provenance { background: #f4f4f4; padding: 20px; margin-top: 40px; border-left: 4px solid #2c5f2d; }
        .citation { margin: 15px 0; padding: 15px; background: white; border: 1px solid #ddd; border-radius: 4px; }
        .citation h3 { margin-top: 0; }
    </style>
</head>
<body>
    <h1>' . esc_html( $post->post_title ) . '</h1>
    <div class="meta">
        Generated by Touchpoint Editorial Planner<br>
        Created: ' . current_time( 'F j, Y' ) . '
    </div>';

        $phase1 = get_post_meta( $post_id, 'kh_planner_phase1_result', true );
        $phase2 = get_post_meta( $post_id, 'kh_planner_phase2_result', true );
        $phase3 = get_post_meta( $post_id, 'kh_planner_phase3_result', true );
        $synopses = get_post_meta( $post_id, 'kh_planner_final_synopses', true );

        if ( ! empty( $phase1['executive_summary'] ) ) {
            $html .= '<h2>Phase 1: Discovery Summary</h2>';
            $html .= '<div class="section"><p>' . nl2br( esc_html( $phase1['executive_summary'] ) ) . '</p>';
            
