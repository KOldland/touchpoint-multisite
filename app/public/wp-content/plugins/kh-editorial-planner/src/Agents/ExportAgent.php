/**
 * ExportAgent
 * 
 * Replaces the legacy Framework_Generator_Exporter.
 * Handles exporting session dossier/briefs to DOCX and HTML formats.
 */
class ExportAgent {

    const EXPORT_DIR = 'editorial_exports';

    /**
     * Export session brief to DOCX
     */
    public function export_to_docx( $post_id ) {
        $post = get_post( $post_id );
        if ( ! $post || $post->post_type !== 'planner_session' ) {
            return new \WP_Error( 'invalid_session', 'Invalid session ID' );
        }

        if ( ! class_exists( 'PhpOffice\\PhpWord\\PhpWord' ) ) {
            return new \WP_Error( 'phpword_not_found', 'PHPWord library not available. Please ensure it is installed.' );
        }

        $phpWord = new \PhpOffice\PhpWord\PhpWord();
        $section = $phpWord->addSection();

        $section->addTitle( $post->post_title, 1 );
        $section->addText( 'Generated by Touchpoint Editorial Planner' );
        $section->addText( 'Created: ' . current_time( 'F j, Y' ) );
        $section->addPageBreak();

        // Retrieve Phase Data
        $phase1 = get_post_meta( $post_id, 'kh_planner_phase1_result', true );
        $phase2 = get_post_meta( $post_id, 'kh_planner_phase2_result', true );
        $phase3 = get_post_meta( $post_id, 'kh_planner_phase3_result', true );
        $synopses = get_post_meta( $post_id, 'kh_planner_final_synopses', true );

        if ( ! empty( $phase1['executive_summary'] ) ) {
            $section->addTitle( 'Phase 1: Discovery Summary', 2 );
            $section->addText( $phase1['executive_summary'] );
            
            if ( ! empty( $phase1['trends'] ) ) {
                $section->addTitle( 'Key Trends Identified', 3 );
                foreach ( $phase1['trends'] as $trend ) {
                    $title = $trend['title'] ?? 'Untitled';
                    $why = $trend['why_it_matters'] ?? '';
                    $section->addText( "• {$title}: {$why}" );
                }
            }
            $section->addTextBreak(1);
        }

        if ( ! empty( $phase2['ranked_keywords'] ) ) {
            $section->addTitle( 'Phase 2: Strategic Keywords', 2 );
            $table = $section->addTable(['borderSize' => 6, 'borderColor' => '999999']);
            $table->addRow();
            $table->addCell(4000)->addText('Keyword', ['bold' => true]);
            $table->addCell(2000)->addText('Volume', ['bold' => true]);
            $table->addCell(2000)->addText('Priority', ['bold' => true]);
            
            foreach ( array_slice( $phase2['ranked_keywords'], 0, 10 ) as $kw ) {
                $table->addRow();
                $table->addCell(4000)->addText( $kw['keyword'] );
                $table->addCell(2000)->addText( $kw['search_volume'] ?? 'N/A' );
                $table->addCell(2000)->addText( $kw['priority_score'] ?? '0' );
            }
            $section->addTextBreak(1);
        }

        if ( ! empty( $phase3['prioritized_topics'] ) ) {
            $section->addTitle( 'Phase 3: Topic Framing', 2 );
            foreach ( $phase3['prioritized_topics'] as $topic ) {
                $section->addTitle( $topic['topic'], 3 );
                $section->addText( "Strategic Intent: " . ( $topic['why_now'] ?? '' ), ['bold' => true] );
                
                if ( ! empty( $topic['key_findings'] ) ) {
                    $section->addText( "Key Findings:", ['bold' => true] );
                    foreach ( $topic['key_findings'] as $finding ) {
                        $section->addText( "• {$finding}" );
                    }
                }
            }
            $section->addTextBreak(1);
        }

        if ( ! empty( $synopses['synopses'] ) ) {
            $section->addTitle( 'Final Article Synopses', 2 );
            foreach ( $synopses['synopses'] as $s ) {
                $headline = $s['headline'] ?? 'Untitled';
                $section->addTitle( "ARTICLE: {$headline}", 3 );
                $section->addText( "Summary: " . ( $s['summary'] ?? '' ) );
                
                if ( ! empty( $s['key_points'] ) ) {
                    $section->addText( "Key Points:", ['bold' => true] );
                    foreach ( (array) $s['key_points'] as $kp ) {
                        $section->addText( "• {$kp}" );
                    }
                }
                $section->addTextBreak(1);
            }
        }

        // Provenance Appendix
        $this->add_provenance_appendix_docx( $section, $post_id );

        $filename = 'session-' . $post_id . '-' . date('Y-m-d-H-i-s') . '.docx';
        $filepath = $this->get_export_path( $filename );

        $objWriter = \PhpOffice\PhpWord\IOFactory::createWriter( $phpWord, 'Word2007' );
        $objWriter->save( $filepath );

        $file_url = $this->get_export_url( $filename );
        update_post_meta( $post_id, 'kh_planner_export_docx_url', $file_url );

        return [
            'file_url' => $file_url,
            'file_path' => $filepath,
            'filename' => $filename,
        ];
    }

    /**
     * Export session brief to HTML
     */
    public function export_to_html( $post_id ) {
        $post = get_post( $post_id );
        if ( ! $post || $post->post_type !== 'planner_session' ) {
            return new \WP_Error( 'invalid_session', 'Invalid session ID' );
        }

        $html = '<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>' . esc_html( $post->post_title ) . '</title>
    <style>
